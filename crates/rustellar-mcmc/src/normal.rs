//! The standard normal's quantile function.

/// The `p` quantile of the standard normal, Wichura's (1988) algorithm
/// AS 241 (PPND16), accurate to about 1e-16 relative: `-inf` at 0, `inf`
/// at 1, NaN outside `[0, 1]`.
#[allow(clippy::unreadable_literal, clippy::excessive_precision)]
pub(crate) fn quantile(p: f64) -> f64 {
    if !(0.0..=1.0).contains(&p) {
        return f64::NAN;
    }
    if p == 0.0 {
        return f64::NEG_INFINITY;
    }
    if p == 1.0 {
        return f64::INFINITY;
    }
    let poly = |c: &[f64], x: f64| c.iter().rev().fold(0.0f64, |acc, &k| acc.mul_add(x, k));
    let q = p - 0.5;
    if q.abs() <= 0.425 {
        let r = q.mul_add(-q, 0.180625);
        let a = [
            3.387132872796366608,
            133.14166789178437745,
            1971.5909503065514427,
            13731.693765509461125,
            45921.953931549871457,
            67265.770927008700853,
            33430.575583588128105,
            2509.0809287301226727,
        ];
        let b = [
            1.0,
            42.313330701600911252,
            687.1870074920579083,
            5394.1960214247511077,
            21213.794301586595867,
            39307.89580009271061,
            28729.085735721942674,
            5226.495278852545925,
        ];
        return q * poly(&a, r) / poly(&b, r);
    }
    let tail = if q < 0.0 { p } else { 1.0 - p };
    let mut r = (-tail.ln()).sqrt();
    let value = if r <= 5.0 {
        r -= 1.6;
        let c = [
            1.42343711074968357734,
            4.6303378461565452959,
            5.7694972214606914055,
            3.64784832476320460504,
            1.27045825245236838258,
            0.24178072517745061177,
            0.0227238449892691845833,
            7.7454501427834140764e-4,
        ];
        let d = [
            1.0,
            2.05319162663775882187,
            1.6763848301838038494,
            0.68976733498510000455,
            0.14810397642748007459,
            0.0151986665636164571966,
            5.475938084995344946e-4,
            1.05075007164441684324e-9,
        ];
        poly(&c, r) / poly(&d, r)
    } else {
        r -= 5.0;
        let e = [
            6.6579046435011037772,
            5.4637849111641143699,
            1.7848265399172913358,
            0.29656057182850489123,
            0.026532189526576123093,
            0.0012426609473880784386,
            2.71155556874348757815e-5,
            2.01033439929228813265e-7,
        ];
        let f = [
            1.0,
            0.59983220655588793769,
            0.13692988092273580531,
            0.0148753612908506148525,
            7.868691311456132591e-4,
            1.8463183175100546818e-5,
            1.4215117583164458887e-7,
            2.04426310338993978564e-15,
        ];
        poly(&e, r) / poly(&f, r)
    };
    if q < 0.0 { -value } else { value }
}
